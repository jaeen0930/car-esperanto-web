/* 글줄을 SVG rect 로 찍는다. 반환: {rects:[[x,y]], cols, rows}  (칸 단위) */
CE.layoutText = function (text) {
  const rects = [];
  [...text].forEach((ch, ci) => {
    const g = CE.PX5[ch] || CE.PX5['-'];
    for (let j = 0; j < 7; j++) for (let i = 0; i < 5; i++) if (g[j][i] === '#') rects.push([ci * 6 + i, j]);
  });
  return { rects, cols: text.length * 6 - 1, rows: 7 };
};
/* <svg> 안을 rect 로 채운다 (rotate: 90 이면 세로쓰기) */
CE.fillSvg = function (svg, text, opts) {
  opts = opts || {};
  const { rects, cols, rows } = CE.layoutText(text);
  const fill = opts.fill || 0.98;
  const d = (1 - fill) / 2;
  let body = '';
  for (const [x, y] of rects) body += `<rect x="${(x + d).toFixed(3)}" y="${(y + d).toFixed(3)}" width="${fill}" height="${fill}"/>`;
  if (opts.rotate === 90) {
    svg.setAttribute('viewBox', `0 0 ${rows} ${cols}`);
    svg.innerHTML = `<g transform="translate(${rows} 0) rotate(90)">${body}</g>`;
  } else {
    svg.setAttribute('viewBox', `0 0 ${cols} ${rows}`);
    svg.innerHTML = body;
  }
};
